# -*- coding: utf-8 -*-
"""
Core SKU generation logic for product.product (variants).

SKU Construction Order:
    Global Sequence Prefix + Selected Template Prefix + Variant-Specific Code + Selected Template Suffix + Global Sequence Suffix

Example:
    Global Sequence Prefix:               GOGAGA-IN-
    Selected Template Prefix:             URB-FUNNY
    Variant-Specific Codes (e.g. Color):  NVY-XL
    Selected Template Suffix:             -MEN-CTCH
    Global Sequence Suffix:               -2026
    ----------------------------------------------------------------------------------------
    Expected Final SKU:                   GOGAGA-IN-URB-FUNNY-NVY-XL-MEN-CTCH-2026
"""

import logging
from datetime import datetime

from odoo import _, api, fields, models
from odoo.exceptions import UserError

_logger = logging.getLogger(__name__)

_PARAM_PREFIX = 'product_sku.prefix'
_PARAM_SUFFIX = 'product_sku.suffix'
_PARAM_SEQ_ID = 'product_sku.sequence_id'


class ProductProduct(models.Model):
    _inherit = 'product.product'

    # ------------------------------------------------------------------
    # Fields
    # ------------------------------------------------------------------

    sku_template_id = fields.Many2one(
        related='product_tmpl_id.sku_template_id',
        string="SKU Infix Template",
        readonly=True,
        store=True,
        help="SKU Infix Template inherited from the Product Template.",
    )

    is_sku_generated = fields.Boolean(
        string="SKU Auto-Generated",
        default=False,
        copy=False,
        help="Tracks whether the Internal Reference was generated by this SKU module.",
    )

    # ------------------------------------------------------------------
    # Button actions
    # ------------------------------------------------------------------

    def action_generate_sku(self):
        """Generate SKU for selected variants that do not yet have one.

        Callable as a button action from the Product Variant form or list.
        Uses product-specific SKU generation if template is configured,
        otherwise uses Fallback SKU Sequence.
        """
        generated = 0
        for variant in self:
            if not variant.default_code:
                new_sku = variant._build_sku()
                if new_sku:
                    variant.write({
                        'default_code': new_sku,
                        'is_sku_generated': True,
                    })
                    generated += 1

        if generated:
            return {
                'type': 'ir.actions.client',
                'tag': 'display_notification',
                'params': {
                    'title': _(""),
                    'message': _(
                        "Internal References generated. %d SKUs generated successfully.",
                        generated,
                    ),
                    'type': 'success',
                    'sticky': False,
                },
            }
        return {
            'type': 'ir.actions.client',
            'tag': 'display_notification',
            'params': {
                'title': _(""),
                'message': _("Internal References generated"),
                'type': 'info',
                'sticky': False,
            },
        }

    def action_clear_sku(self):
        """Open the Clear Generated SKUs confirmation wizard for this variant."""
        self.ensure_one()
        return {
            'name': _("Clear Generated SKU"),
            'type': 'ir.actions.act_window',
            'res_model': 'sku.clear.wizard',
            'view_mode': 'form',
            'target': 'new',
            'context': {
                'default_product_id': self.id,
            },
        }

    def action_force_regenerate_sku(self):
        """Force-regenerate SKU even when default_code is already set."""
        for variant in self:
            new_sku = variant._build_sku(force=True)
            if new_sku:
                variant.write({
                    'default_code': new_sku,
                    'is_sku_generated': True,
                })

    # ------------------------------------------------------------------
    # Core builder
    # ------------------------------------------------------------------

    def _build_sku(self, force=False):
        """Build and return a new SKU string for self (single record).

        Order:
            Global Sequence Prefix + Product-Specific SKU Infix + Variant-Specific SKU Codes + Global Sequence Suffix

        Example:
            Global Sequence Prefix:               GOGAGA-IN-
            Product-Specific SKU Infix:           URB-FUNNY-MEN-CTSH-PLAIN-
            Variant-Specific SKU Codes:           NVY-XL
            Global Sequence Suffix:               -2026
            ----------------------------------------------------------------------------------------
            Expected Final SKU:                   GOGAGA-IN-URB-FUNNY-MEN-CTSH-PLAIN-NVY-XL-2026

        :param bool force: If True, generate even when default_code exists.
        :rtype: str | bool
        """
        self.ensure_one()

        if self.default_code and not force:
            return False

        template = self.with_context(active_test=False).sku_template_id
        # Fallback condition: If no template, inactive template (Active = OFF), or no infix configured,
        # automatically use the Fallback SKU Sequence selected in Settings
        if not template or not template.active or not (template.clean_infix() or template.clean_prefix()):
            return self._build_fallback_sku(force=force)

        # Retrieve centralized Global SKU Sequence
        seq = self.env['ir.sequence'].search([
            ('code', '=', 'product.sku.global'),
            ('active', '=', True),
        ], limit=1)
        if not seq:
            seq_ref = self.env.ref('product_sku_enhancements.seq_product_sku_global', raise_if_not_found=False)
            if seq_ref and seq_ref.active:
                seq = seq_ref

        if not seq or not seq.active:
            raise UserError(_(
                "Global SKU Sequence configuration is missing or inactive. "
                "Please configure an active sequence with code 'product.sku.global' "
                "under Settings → Technical → Sequences & Identifiers → Sequences."
            ))

        # Read and resolve configured prefix and suffix without consuming sequence counter
        try:
            raw_global_prefix, raw_global_suffix = seq._get_prefix_suffix()
        except UserError:
            raw_global_prefix = seq.prefix or ''
            raw_global_suffix = seq.suffix or ''
        global_prefix = self._apply_sku_placeholders(raw_global_prefix)
        global_suffix = self._apply_sku_placeholders(raw_global_suffix)

        # Product-Specific SKU Infix
        product_sku_infix = template.clean_infix()

        # Variant attribute segments (e.g. ['BLK', 'XS'])
        var_segments = self._get_variant_sku_segments()
        var_code = '-'.join(var_segments) if var_segments else ''

        # Combine in exact order:
        # Global Prefix + Product-Specific SKU Infix + Variant-Specific SKU Codes + Global Suffix
        raw_parts = [global_prefix, product_sku_infix, var_code, global_suffix]

        # Normalize whitespace and separators to avoid unintended duplicate hyphens
        cleaned_parts = []
        for part in raw_parts:
            if part:
                cleaned = part.strip().strip('-')
                if cleaned:
                    cleaned_parts.append(cleaned)

        base_sku = '-'.join(cleaned_parts)

        # Guarantee unique SKU across all products/variants without sequence numbering for ordinary SKUs
        return self._ensure_unique_sku(base_sku)

    def _build_fallback_sku(self, force=False):
        """Generate a fallback SKU using the configured Fallback SKU Sequence.

        Used when SKU Product Code Active = OFF, or when product has no SKU Product Code assigned.
        Does not overwrite existing valid manually assigned Internal References.
        """
        self.ensure_one()
        if self.default_code and not force:
            return False

        IrParam = self.env['ir.config_parameter'].sudo()
        seq_id = IrParam.get_param(_PARAM_SEQ_ID)
        sequence = False
        if seq_id:
            try:
                sequence = self.env['ir.sequence'].browse(int(seq_id))
            except (ValueError, TypeError):
                sequence = False

        if not sequence or not sequence.exists() or not sequence.active:
            raise UserError(_(
                "No active Fallback SKU Sequence is configured. "
                "Please configure a valid sequence under Inventory → Configuration → Settings → Fallback SKU Sequence Configuration."
            ))

        next_code = self._next_fallback_code(sequence)
        return self._ensure_unique_sku(next_code)

    def _next_fallback_code(self, sequence):
        """Obtain the next code from the fallback sequence safely.

        Uses sequence.next_by_id(), incrementing the sequence number and respecting
        padding, step, prefix, and suffix. If prefix/suffix contains legacy placeholders
        (e.g. %YEAR), it resolves them safely using _apply_sku_placeholders.
        """
        try:
            next_code = sequence.next_by_id()
        except UserError as e:
            if 'Invalid prefix or suffix' in str(e):
                if sequence.implementation == 'standard':
                    from odoo.addons.base.models.ir_sequence import _select_nextval
                    number_next = _select_nextval(self.env.cr, 'ir_sequence_%03d' % sequence.id)
                else:
                    from odoo.addons.base.models.ir_sequence import _update_nogap
                    number_next = _update_nogap(sequence, sequence.number_increment)

                prefix = self._apply_sku_placeholders(sequence.prefix or '')
                suffix = self._apply_sku_placeholders(sequence.suffix or '')
                num_str = ('%%0%sd' % sequence.padding) % number_next
                next_code = f"{prefix}{num_str}{suffix}"
            else:
                raise

        if not next_code:
            raise UserError(_(
                "Failed to generate SKU from Fallback SKU Sequence '%s'.",
                sequence.name,
            ))
        return next_code

    def _ensure_unique_sku(self, base_sku):
        """Ensure base_sku is unique across product.product records.

        If another record already has this default_code, append a dash-increment counter (-02, -03...)
        so that duplicates are never generated. Ordinary SKUs do not have sequence numbering unless
        a duplicate collision occurs.
        """
        sku = base_sku
        counter = 1
        while self.env['product.product'].search_count([
            ('default_code', '=', sku),
            ('id', '!=', self.id),
        ]) > 0:
            counter += 1
            sku = f"{base_sku}-{counter:02d}"
        return sku

    # ------------------------------------------------------------------
    # Variant segment extraction
    # ------------------------------------------------------------------

    def _get_variant_sku_segments(self):
        """Return a list of SKU segment strings for this variant's attributes.

        Only attributes with create_variant != 'no_variant' are included,
        ordered consistently by attribute_line sequence and id.
        """
        self.ensure_one()
        segments = []
        for ptav in self.product_template_attribute_value_ids.sorted(
            key=lambda v: (v.attribute_line_id.sequence, v.attribute_line_id.id)
        ):
            if ptav.attribute_id.create_variant == 'no_variant':
                continue
            pav = ptav.product_attribute_value_id
            segments.append(pav._get_sku_segment())
        return segments

    # ------------------------------------------------------------------
    # Placeholder replacement
    # ------------------------------------------------------------------

    @api.model
    def _apply_sku_placeholders(self, raw_text):
        """Replace known placeholders in raw_text and return result.

        Supported placeholders:
            %YEAR, %Y, %(year)s, %(y)s -> current calendar year (4 digits)
            %MONTH, %m                 -> current calendar month (2 digits)
            %DAY, %d                   -> current calendar day (2 digits)
        """
        if not raw_text:
            return ''
        now = datetime.now()
        year_str = str(now.year)
        month_str = f"{now.month:02d}"
        day_str = f"{now.day:02d}"

        result = raw_text.replace('%YEAR', year_str)\
                         .replace('%Y', year_str)\
                         .replace('%(year)s', year_str)\
                         .replace('%(y)s', year_str)\
                         .replace('%MONTH', month_str)\
                         .replace('%m', month_str)\
                         .replace('%DAY', day_str)\
                         .replace('%d', day_str)
        return result
